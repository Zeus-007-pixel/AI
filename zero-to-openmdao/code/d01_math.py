print(7 + 2)     # addition
print(7 - 2)     # subtraction
print(7 * 2)     # multiplication
print(7 / 2)     # division
print(7 // 2)    # whole-number division (drops the decimals)
print(7 % 2)     # remainder after division
print(7 ** 2)    # power: 7 squared
print((7 + 2) * 3)
print(1.5e3)     # scientific notation: 1.5 x 10^3
