mach = 6.2

print(mach > 5)          # greater than
print(mach < 5)          # less than
print(mach == 6.2)       # equal to (two = signs!)
print(mach != 6.2)       # not equal to
print(mach >= 1 and mach <= 10)   # both must be True
print(mach < 1 or mach > 5)       # at least one must be True
print(not mach > 5)               # flips True/False
